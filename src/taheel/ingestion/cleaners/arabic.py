"""
Engine-Aware Arabic Text Cleaner & Normalization Engine for Taheel AI (تأهيل).

Tailored for Vision-Language OCR (Baidu Unlimited-OCR / Vision LLMs):
- Preserves Markdown structure, headers, tables, and lists.
- Strips tatweel (kashida), invisible BiDi marks (RLM, LRM), and zero-width artifacts.
- Normalizes Arabic punctuation (، ؟ ؛) while strictly protecting technical symbols and code blocks.
- Semantic Matching Normalizer: Unifies Alef variants, Taa Marbuta, Yaa, and strips tashkeel.
"""

from __future__ import annotations
import re
import unicodedata
from typing import List

# Tashkeel / Harakat (Diacritics)
TASHKEEL_REGEX = re.compile(r"[\u0617-\u061A\u064B-\u0652\u0670]")

# Tatweel / Kashida
TATWEEL_REGEX = re.compile(r"\u0640+")

# Invisible Unicode Directional Marks & Formatting Controls
INVISIBLE_BIDI_REGEX = re.compile(r"[\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]")

# Canonical Arabic Script Range
ARABIC_CHAR_REGEX = re.compile(r"[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF]")


def detect_arabic_ratio(text: str) -> float:
    """Calculates ratio of Arabic characters to total alphabetical characters."""
    if not text:
        return 0.0
    total_alpha = 0
    arabic_count = 0
    for ch in text:
        if ch.isalpha():
            total_alpha += 1
            if '\u0600' <= ch <= '\u06FF' or '\u0750' <= ch <= '\u077F' or '\u08A0' <= ch <= '\u08FF':
                arabic_count += 1
    return arabic_count / total_alpha if total_alpha > 0 else 0.0


def is_arabic_text(text: str, threshold: float = 0.3) -> bool:
    """Returns True if Arabic character ratio meets or exceeds threshold."""
    return detect_arabic_ratio(text) >= threshold


def strip_tashkeel(text: str) -> str:
    """Removes all Arabic diacritical marks."""
    return TASHKEEL_REGEX.sub("", text)


def strip_tatweel(text: str) -> str:
    """Removes Arabic elongation marks (tatweel/kashida: ـ)."""
    return TATWEEL_REGEX.sub("", text)


def strip_bidi_marks(text: str) -> str:
    """Removes invisible RTL/LTR markers and zero-width joiners."""
    return INVISIBLE_BIDI_REGEX.sub("", text)


def clean_vision_ocr_markdown(text: str) -> str:
    """
    Cleans and polishes structured Markdown generated by Baidu Unlimited-OCR.
    Preserves tables, code fences, headers, while normalizing Arabic prose punctuation.
    """
    if not text:
        return ""

    cleaned = strip_bidi_marks(text)
    cleaned = strip_tatweel(cleaned)
    cleaned = unicodedata.normalize("NFC", cleaned)

    lines = cleaned.splitlines()
    processed_lines: List[str] = []
    in_code_block = False

    for line in lines:
        stripped = line.rstrip()

        if stripped.startswith("```"):
            in_code_block = not in_code_block
            processed_lines.append(stripped)
            continue

        if in_code_block:
            processed_lines.append(line)
            continue

        if stripped.startswith("|"):
            cells = [re.sub(r"\s+", " ", c).strip() for c in stripped.split("|")]
            line_cleaned = " | ".join(cells).strip()
            if not line_cleaned.startswith("|"):
                line_cleaned = f"| {line_cleaned}"
            if not line_cleaned.endswith("|"):
                line_cleaned = f"{line_cleaned} |"
            processed_lines.append(line_cleaned)
            continue

        line_cleaned = re.sub(r"[ \t]+", " ", stripped)

        if is_arabic_text(line_cleaned, threshold=0.4):
            line_cleaned = re.sub(r"([\u0600-\u06FF])\s*\?", r"\1 ؟", line_cleaned)
            line_cleaned = re.sub(r"([\u0600-\u06FF])\s*,\s*", r"\1، ", line_cleaned)
            line_cleaned = re.sub(r"([\u0600-\u06FF])\s*;\s*", r"\1؛ ", line_cleaned)

        processed_lines.append(line_cleaned)

    result = "\n".join(processed_lines)
    result = re.sub(r"\n{3,}", "\n\n", result)
    return result.strip()


def normalize_for_matching(text: str) -> str:
    """Aggressive normalization for semantic search and ontology filtering."""
    if not text:
        return ""

    normalized = strip_tashkeel(text)
    normalized = strip_tatweel(normalized)
    normalized = strip_bidi_marks(normalized)
    normalized = unicodedata.normalize("NFC", normalized)

    normalized = re.sub(r"[أإآٱ]", "ا", normalized)
    normalized = re.sub(r"ة", "ه", normalized)
    normalized = re.sub(r"ى", "ي", normalized)

    indic_to_arabic = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")
    normalized = normalized.translate(indic_to_arabic)
    normalized = normalized.lower()
    normalized = re.sub(r"\s+", " ", normalized).strip()
    return normalized
