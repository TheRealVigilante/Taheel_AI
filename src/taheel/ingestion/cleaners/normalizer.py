"""
Unified Bilingual Normalization Coordinator for Taheel AI (تأهيل).

Coordinates Arabic and English text cleaning pipelines:
- Automatically detects document language mix (pure Arabic, pure English, or code-switched bilingual).
- Dispatches to specialized cleaners while ensuring seamless mixed-language coherence.
"""

from __future__ import annotations
import re
from typing import Literal

from src.taheel.ingestion.cleaners.arabic import (
    clean_vision_ocr_markdown as clean_ar_markdown,
    detect_arabic_ratio,
)
from src.taheel.ingestion.cleaners.english import (
    clean_vision_ocr_markdown as clean_en_markdown,
    unfold_english_ligatures,
    dehyphenate_english_text,
    normalize_english_typography,
)


def detect_primary_language(text: str) -> Literal["ar", "en", "bilingual"]:
    """
    Detects whether text is primarily Arabic, English, or a mixed bilingual document.
    - ar: Arabic ratio >= 0.6
    - en: Arabic ratio <= 0.15
    - bilingual: Arabic ratio between 0.15 and 0.6
    """
    ratio = detect_arabic_ratio(text)
    if ratio >= 0.6:
        return "ar"
    elif ratio <= 0.15:
        return "en"
    return "bilingual"


def clean_bilingual_markdown(text: str) -> str:
    """
    High-level entry point for cleaning Markdown generated by Baidu Unlimited-OCR.
    Handles pure English, pure Arabic, and mixed code-switching documents.
    """
    if not text:
        return ""

    # 1. English pass: unfold Latin ligatures and normalize typography
    text = unfold_english_ligatures(text)
    text = normalize_english_typography(text)
    text = dehyphenate_english_text(text)

    # 2. Arabic pass: strip tatweel, BiDi marks, normalize Arabic punctuation
    text = clean_ar_markdown(text)

    return text.strip()
