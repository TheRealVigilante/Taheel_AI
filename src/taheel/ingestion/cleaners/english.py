"""
English Text Cleaner & Normalization Engine for Taheel AI (تأهيل).

Handles English-specific document anomalies from PDF streams and OCR:
1. De-hyphenation of line-wrapped words (e.g. 'recon-\\nciliation' -> 'reconciliation').
2. Unfolding of Latin typographic ligatures (ﬁ, ﬂ, ﬀ, ﬃ, ﬄ -> fi, fl, ff, ffi, ffl).
3. Normalization of smart quotes, em/en dashes, and Unicode whitespace.
4. Stripping of repeating page boilerplate (e.g., 'Page X of Y', confidentiality disclaimers).
5. Protection of technical SOP identifiers, code blocks, and markdown tables.
"""

from __future__ import annotations
import re
import unicodedata
from typing import List, Dict

# Latin Typographic Ligature Map
LATIN_LIGATURE_MAP: Dict[str, str] = {
    "\ufb00": "ff",
    "\ufb01": "fi",
    "\ufb02": "fl",
    "\ufb03": "ffi",
    "\ufb04": "ffl",
    "\ufb05": "ft",
    "\ufb06": "st",
    "\u0152": "OE",
    "\u0153": "oe",
    "\u00c6": "AE",
    "\u00e6": "ae",
}

# Typography replacement tables
SMART_QUOTES_MAP = str.maketrans({
    "“": '"', "”": '"', "„": '"', "«": '"', "»": '"',
    "‘": "'", "’": "'", "‚": "'", "‛": "'",
    "`": "'",
})

# Boilerplate header/footer patterns
BOILERPLATE_PATTERNS = [
    re.compile(r"(?i)^\s*Page\s+\d+\s+(?:of|/)\s+\d+\s*$", re.MULTILINE),
    re.compile(r"(?i)^\s*Page\s+\d+\s*$", re.MULTILINE),
    re.compile(r"(?i)^\s*(?:Confidential|Internal Only|Strictly Confidential|All Rights Reserved)(?:\s*[-–—]\s*.*)?$", re.MULTILINE),
]


def unfold_english_ligatures(text: str) -> str:
    """Unfolds Latin typographical ligatures (fi, fl, ff, etc.) into ASCII letter pairs."""
    if not text:
        return ""
    for ligature, replacement in LATIN_LIGATURE_MAP.items():
        text = text.replace(ligature, replacement)
    return text


def normalize_english_typography(text: str) -> str:
    """
    Normalizes curly quotes, em/en dashes, ellipses, and irregular Unicode spaces
    to standard Markdown equivalents.
    """
    if not text:
        return ""

    # 1. Normalize smart quotes
    text = text.translate(SMART_QUOTES_MAP)

    # 2. Normalize dashes (em-dash, en-dash, figure dash -> hyphen)
    text = re.sub(r"[\u2010-\u2015]", "-", text)

    # 3. Normalize ellipsis
    text = text.replace("…", "...")

    # 4. Normalize irregular whitespace (non-breaking spaces, en-spaces, em-spaces)
    text = re.sub(r"[\u00A0\u1680\u2000-\u200A\u202F\u205F\u3000]", " ", text)

    return text


def dehyphenate_english_text(text: str) -> str:
    """
    Rejoins words split by a line-end hyphen and newline.
    e.g. 'recon-\\nciliation' -> 'reconciliation'
    
    Protects:
    - Markdown lists (- [ ] or - item)
    - Compound words with spaces or capital letters (e.g. 'Tier-1')
    """
    if not text:
        return ""

    # Matches word characters of at least 2 letters followed by hyphen, newline, and at least 2 lowercase letters
    return re.sub(r"([a-zA-Z]{2,})-\n\s*([a-z]{2,})", r"\1\2", text)


def strip_english_boilerplate(text: str) -> str:
    """Removes common repeating PDF headers and footers (page numbers, disclaimers)."""
    if not text:
        return ""
    for pattern in BOILERPLATE_PATTERNS:
        text = pattern.sub("", text)
    return text


def clean_vision_ocr_markdown(text: str) -> str:
    """
    Cleans structured English Markdown generated by Baidu Unlimited-OCR.
    Protects code blocks, table borders, and de-hyphenates prose.
    """
    if not text:
        return ""

    # 1. Unfold ligatures and normalize quotes/dashes
    cleaned = unfold_english_ligatures(text)
    cleaned = normalize_english_typography(cleaned)

    # 2. Dehyphenate broken words across line breaks
    cleaned = dehyphenate_english_text(cleaned)

    # 3. Strip page boilerplate
    cleaned = strip_english_boilerplate(cleaned)

    # 4. Clean line by line while preserving code blocks and tables
    lines = cleaned.splitlines()
    processed_lines: List[str] = []
    in_code_block = False

    for line in lines:
        stripped = line.rstrip()

        # Track markdown code fences
        if stripped.startswith("```"):
            in_code_block = not in_code_block
            processed_lines.append(stripped)
            continue

        if in_code_block:
            processed_lines.append(line)
            continue

        if stripped.startswith("|"):
            # Clean spaces within markdown table cells
            cells = [re.sub(r"\s+", " ", c).strip() for c in stripped.split("|")]
            line_cleaned = " | ".join(cells).strip()
            if not line_cleaned.startswith("|"):
                line_cleaned = f"| {line_cleaned}"
            if not line_cleaned.endswith("|"):
                line_cleaned = f"{line_cleaned} |"
            processed_lines.append(line_cleaned)
            continue

        # Normal prose line: normalize horizontal spaces
        line_cleaned = re.sub(r"[ \t]+", " ", stripped)
        processed_lines.append(line_cleaned)

    result = "\n".join(processed_lines)
    result = re.sub(r"\n{3,}", "\n\n", result)
    return result.strip()
